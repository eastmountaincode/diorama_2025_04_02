import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';

const projectRoot = resolve(import.meta.dirname, '..');
const publicRoot = join(projectRoot, 'public');
const assetRoot = join(publicRoot, 'assets');
const outputPath = join(projectRoot, 'src', 'generated', 'gameAssets.ts');

function collectFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => !entry.name.startsWith('.'))
    .flatMap((entry) => {
      const entryPath = join(directory, entry.name);
      return entry.isDirectory() ? collectFiles(entryPath) : [entryPath];
    });
}

const assets = collectFiles(assetRoot)
  .map((filePath) => `/${relative(publicRoot, filePath).split(sep).join('/')}`)
  .sort((left, right) => left.localeCompare(right));

const generatedSource = `// This file is generated by scripts/generate-asset-manifest.mjs.\n` +
  `// Run npm run generate:asset-manifest after adding or removing public assets.\n\n` +
  `export const GAME_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, generatedSource);

console.log(`Generated ${assets.length} game asset paths.`);
